import { chromium } from "playwright";
const BASE = process.env.BASE_URL ?? "http://localhost:3100";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 320, height: 720 }, extraHTTPHeaders: { "x-forwarded-for": `10.9.${Math.floor(Math.random() * 255)}.${Math.floor(Math.random() * 254) + 1}` } });
page.on("request", (r) => { if (r.method() === "POST") { const d = r.postData() ?? ""; console.log("POST", r.url().replace(BASE, ""), "len", d.length, d.replace(/\r?\n/g, " ").slice(0, 400)); } });
page.on("console", (m) => m.type() === "error" && console.log("console:", m.text().slice(0, 160)));
await page.goto(`${BASE}/contact`);
await page.getByLabel(/^name/i).fill("E2E Tester");
await page.getByLabel(/^email/i).fill("not-an-email");
await page.getByLabel(/subject/i).fill("Playwright check");
await page.getByLabel(/^message/i).fill("Short");
await page.getByRole("button", { name: /send message/i }).click();
await page.getByRole("alert").first().waitFor();
console.log("alert visible at", Date.now() % 100000);
await page.getByLabel(/^email/i).fill(`e2e+${Date.now()}@example.com`);
await page.getByLabel(/^message/i).fill("This is an automated end-to-end test message with enough characters.");
await page.getByLabel(/i agree/i).check();
const snapshot = await page.evaluate(() => ({ email: document.querySelector("input[name=email]")?.value, msg: document.querySelector("textarea[name=message]")?.value?.slice(0, 20), consent: document.querySelector("input[name=consent]")?.checked, forms: document.querySelectorAll("form").length }));
console.log("before submit", JSON.stringify(snapshot));
await page.getByRole("button", { name: /send message/i }).click();
await page.waitForTimeout(4000);
const after = await page.evaluate(() => ({ email: document.querySelector("input[name=email]")?.value, consent: document.querySelector("input[name=consent]")?.checked, alert: document.querySelector("[role=alert]")?.textContent?.slice(0, 120), status: document.querySelector("[role=status]")?.textContent?.slice(0, 80) }));
console.log("after", JSON.stringify(after));
await browser.close();

/**
 * Initial portfolio roster. Only facts supplied by the owner are stated. Everything else is
 * described as capability or marked pending. Screenshots for public sites are captured by
 * `npm run screenshots` into /public/screenshots/<slug>/ and referenced here.
 */

function shot(slug: string, file: string, alt: string, pageLabel: string, device: "desktop" | "mobile", order: number, caption?: string): ProjectMedia {
  const isMobile = device === "mobile";
  return {
    id: `${slug}-${file.replace(/\.[a-z]+$/, "")}`,
    src: `/screenshots/${slug}/${file}`,
    alt,
    caption,
    kind: "screenshot",
    pageLabel,
    device,
    isAuthenticScreenshot: true,
    approvedForPublication: true,
    width: isMobile ? 390 : 1440,
    height: isMobile ? 844 : 900,
    sortOrder: order,
  };
}

